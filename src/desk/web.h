/* Miaou Web engine - shared declarations: DOM, CSS, layout, JavaScript (mujs, ES5). */
#ifndef MIAOU_WEB_H
#define MIAOU_WEB_H
#include <stddef.h>
#include "desk.h"

enum { D_INLINE, D_BLOCK, D_NONE, D_LISTITEM, D_IBLOCK, D_ROW };

typedef struct {
    u32 color, bg, bc;
    unsigned char has_bg, bold, italic, ul, strike, align, display, pre, upper, lower, hidden, mono, nowrap, jcenter, col, automl, automr, bsides, sticky_dummy;
    unsigned char bbox, nolist, flexwrap, aitems, pos, isgrid, ngtrack, gautofill, hide_opacity;
    short fs, mt, mb, ml, mr, pt, pb, pl, pr, bw, width, maxw, minw, height, wpct, wadd, radius, lh;
    short fgrow, fbasis, rgap, cgap, gtrack[10], gmin;           /* flex-grow, flex-basis (px, 0 = auto), gaps, grid column tracks (px >0, fr*10 <0), auto-fill minimum */
} Style;

typedef struct Node Node;
struct Node {
    int type;                       /* 0 element, 1 text */
    char tag[16];
    char *text;
    char *an[14], *av[14]; int na;
    Node *parent, *first, *last, *next, *prev;
    Style st;
    char *jsref;
    unsigned char gen;                 /* generated by ::before / ::after */
};

enum { DI_FILL, DI_BORDER, DI_TEXT, DI_LINE, DI_FIELD, DI_BOX };
typedef struct { int kind, x, y, w, h; u32 c, c2; char *s; Font *f; int px, ul, strike, radius; Node *node; } DI;

typedef struct { char *decl; int spec, order; void *sel; } Rule;

typedef struct { int id; long due, every; void *fn; } Timer;

typedef struct Page {
    Node *doc;
    Node **all; int nall, capall;
    char url[700], title[128], base[700];
    Rule *rules; int nrules, caprules;
    char *vk[48], *vv[48]; int nvars;
    DI *di; int ndi, capdi;
    int height, layout_w, dirty, pending_nav;
    char nav_url[700];
    void *J;                                   /* js_State* */
    Timer timers[32]; int ntimers, next_timer;
    Node *focus, *hover;
    int has_hover;
    char console[6][160]; int ncons;
    char err[160];
    int post_pending; char post_data[1200];
    long js_deadline;                          /* watchdog: scripts are interrupted after this time (ms clock) */
    char *(*fetch)(const char *url, size_t *len, void *ctx); void *fctx;     /* synchronous resource loader (scripts, stylesheets, XHR) */
} Page;

/* dom */
Node *wn_new(Page *p, int type, const char *tag);
void wn_append(Node *parent, Node *c);
void wn_unlink(Node *c);
void wn_insert_before(Node *parent, Node *c, Node *ref);
const char *wn_attr(const Node *n, const char *k);
void wn_set_attr(Node *n, const char *k, const char *v);
void wn_del_attr(Node *n, const char *k);
void wn_parse(Page *p, const char *html, Node *parent);
char *wn_text(const Node *n);                 /* malloc'd textContent */
void wn_set_text(Page *p, Node *n, const char *s);
char *wn_inner_html(const Node *n);
void wn_set_inner_html(Page *p, Node *n, const char *html);
char *wn_decode(const char *s, size_t n);
Node *wn_find_tag(Node *root, const char *tag);
void page_free(Page *p);
Page *page_new(void);

/* css */
void css_add_sheet(Page *p, const char *css);
void css_cascade(Page *p);
Node *css_query_first(Node *root, const char *sel);
int css_query_all(Node *root, const char *sel, Node **out, int max);
void css_style_prop(Node *n, const char *prop, const char *val);      /* inline style set */
char *css_style_get(const Node *n, const char *prop);
u32 css_color(const char *s, int *ok);

/* layout */
void lay_page(Page *p, int width);
void lay_paint(Page *p, int x, int y, int w, int h, int scroll);
Node *lay_hit(Page *p, int px, int py);          /* element under a content point (page coords) */

/* js */
void js_page_init(Page *p);
void js_page_free(Page *p);
void js_run_scripts(Page *p);
void js_run_timers(Page *p);
int  js_dispatch(Page *p, Node *target, const char *type, const char *key);   /* returns 1 if default prevented */
int  js_run_inline(Page *p, Node *n, const char *code);
void js_log(Page *p, const char *msg);
#endif
